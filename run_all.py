"""
run_all.py
----------
Runs the whole project from start to finish:

    python run_all.py              # uses the data already in data/raw
    python run_all.py --download   # downloads fresh data from NOAA first

Steps
  1. (optional) download data from NOAA          -> data/raw/
  2. clean the data, build yearly numbers        -> data/processed/
  3. station quality check + station map         -> figures/fig01, fig02
  4. Angle 1: WHERE is it warming most?          -> figures/fig03-fig06
  5. Angle 2: WHEN - day or night, which season? -> figures/fig07-fig08
  6. Angle 3: WHAT do people feel - extremes?    -> figures/fig09-fig12
  7. write a short summary                       -> results/key_findings.md
"""

import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))

import config                     # noqa: E402
import download_data              # noqa: E402
import clean_data                 # noqa: E402
import quality_check              # noqa: E402
import angle1_where               # noqa: E402
import angle2_when                # noqa: E402
import angle3_extremes            # noqa: E402


def step(title):
    print("\n" + "=" * 70 + f"\n{title}\n" + "=" * 70)


def write_summary(a1, a2, a3):
    hot, warm, frz, ffs = (a3[k] for k in
                           ["hot_days", "warm_nights", "freeze_days", "freeze_free_days"])
    lines = [
        "# Key findings (generated by run_all.py)",
        "",
        "Data: NOAA NCEI GHCN-Daily, 10 South Carolina stations, 1966-2025.",
        "Sumter was flagged by the neighbour check and left out of temperature averages.",
        "",
        "## Angle 1 - Where is it warming most?",
        f"- Statewide warming: **+{a1['statewide_f_per_decade']:.2f} °F per decade** "
        f"(± {a1['statewide_ci95']:.2f}, p = {a1['statewide_p']:.1e}), "
        f"about +{a1['statewide_f_per_decade'] * 6:.1f} °F over 60 years.",
        f"- Fastest: **{a1['fastest_city']}** (+{a1['fastest_rate']:.2f} °F/decade). "
        f"Slowest trusted station: {a1['slowest_trusted_city']} "
        f"(+{a1['slowest_trusted_rate']:.2f}).",
        f"- {a1['n_significant']} of {a1['n_trusted']} trusted stations have a significant "
        "warming trend (p < 0.05).",
        f"- Region averages (°F/decade): Coast {a1['region_Coast']:.2f}, "
        f"Midlands {a1['region_Midlands']:.2f}, Upstate {a1['region_Upstate']:.2f}.",
        "",
        "## Angle 2 - When: day or night, which season?",
        f"- Nights (daily low) warm at +{a2['avg_lows_f_per_decade']:.2f} °F/decade vs. "
        f"days (daily high) +{a2['avg_highs_f_per_decade']:.2f} °F/decade on average.",
        f"- Nights warm faster than days in {a2['cities_nights_faster']} of "
        f"{a2['n_trusted']} cities - biggest gaps in downtown Charleston and Columbia.",
        f"- Winter is warming {a2['winter_vs_rest_ratio']:.1f}x faster than the other seasons.",
        "",
        "## Angle 3 - What do people feel: extremes",
        f"- Hot days (≥95 °F): {hot[0]:.1f} → {hot[1]:.1f} per year (p = {hot[2]:.3f}).",
        f"- Warm nights (≥75 °F): {warm[0]:.1f} → {warm[1]:.1f} per year (p = {warm[2]:.1e}).",
        f"- Freeze days (≤32 °F): {frz[0]:.1f} → {frz[1]:.1f} per year (p = {frz[2]:.1e}).",
        f"- Freeze-free season: {ffs[0]:.0f} → {ffs[1]:.0f} days (p = {ffs[2]:.1e}).",
        f"- Heavy rain days (≥2 in): no significant trend (p = {a3['heavy_rain_trend_p']:.2f}).",
    ]
    path = config.RESULTS_DIR / "key_findings.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main():
    start = time.time()
    raw_files = list(config.RAW_DIR.glob("*.csv"))
    if "--download" in sys.argv or len(raw_files) < len(config.STATIONS):
        step("Step 1  Download data from NOAA")
        download_data.main()
    else:
        step("Step 1  Using the data already in data/raw (add --download for fresh data)")

    step("Step 2  Clean data and build yearly numbers")
    clean_data.main()

    step("Step 3  Station quality check and map")
    quality_check.main()

    step("Step 4  Angle 1 - WHERE is South Carolina warming most?")
    a1 = angle1_where.main()

    step("Step 5  Angle 2 - WHEN: day or night, which season?")
    a2 = angle2_when.main()

    step("Step 6  Angle 3 - WHAT do people feel: extreme days")
    a3 = angle3_extremes.main()

    step("Step 7  Summary")
    write_summary(a1, a2, a3)
    print(f"\nAll done in {time.time() - start:.0f} s. "
          f"Figures are in {config.FIG_DIR}, tables in {config.RESULTS_DIR}.")


if __name__ == "__main__":
    main()
